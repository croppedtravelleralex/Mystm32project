#ifndef __FONT_H__
#define __FONT_H__

#include "stm32f10x.h"

/*
 * ===== 5×7 ASCII 字模表 =====
 *
 * 编码：每个字符用 5 个 uint8_t 表示（5 列 × 7 行），
 *       每个字节的低 7 位表示一列的 7 个像素点（bit0=最上行）。
 *
 * 生成方法：
 *   使用 PCtoLCD2002 等字模软件，设置：
 *     字模格式：横向5×7点阵
 *     取模方式：列行式（C51格式 / 阴码 / 逐列式）
 *     每字节低位在上
 *   或者手绘：在一张 5×7 的表格上涂黑像素，按列编码。
 *
 * 示例（字符 'A'，5×7）：
 *
 *    列0 列1 列2 列3 列4
 *     .   #   #   #   .     ← bit6 (行0)
 *     #   .   .   .   #     ← bit5 (行1)
 *     #   .   .   .   #     ← bit4 (行2)
 *     #   #   #   #   #     ← bit3 (行3)
 *     #   .   .   .   #     ← bit2 (行4)
 *     #   .   .   .   #     ← bit1 (行5)
 *     #   .   .   .   #     ← bit0 (行6)
 *
 *   列0: 01000100 = 0x44
 *   列1: 00101000 = 0x28
 *   列2: 00010000 = 0x10  （但通常取整列 byte，行0在LSB还是MSB取决于取模方向）
 *
 *   本表中使用**纵向取模、低位在上**（LSB = 行0），
 *   即每个字节的 bit0 对应 OLED 页内的行0。
 *
 * 包含范围：ASCII 0x20~0x7E（空格到 ~ 共 95 个字符）
 *
 * 6×8 字体使用说明：
 *   6×8 字体 = 5×7 点阵 + 右侧 1 列空白（字符间距），
 *   显示时每个字符占 6 像素宽，8 像素高。
 *   本表直接给 5 字节数据，显示函数在末尾补 1 空白列即可实现 6×8 效果。
 */

/* 字符宽度（点阵列数，不含间距） */
#define FONT_5X7_WIDTH      5

/* 字符高度（点阵行数） */
#define FONT_5X7_HEIGHT     7

/* 每字符字节数 */
#define FONT_5X7_BYTES      5

/* 字模数组声明 */
extern const uint8_t Font_5x7[95][FONT_5X7_BYTES];

/*
 * ===== 8×16 ASCII 字模表 =====
 *
 * 更大的字体，每个字符 8 像素宽 × 16 像素高。
 * 占用 2 个 OLED 页（每页 8 行）。
 * 适合标题行或需要突出的数字。
 *
 * 编码：每个字符 16 字节（上半页 8 字节 + 下半页 8 字节）
 */

#define FONT_8X16_WIDTH     8
#define FONT_8X16_HEIGHT    16
#define FONT_8X16_BYTES     16

extern const uint8_t Font_8x16[95][FONT_8X16_BYTES];

#endif  //__FONT_H__
